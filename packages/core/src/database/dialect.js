/**
 * Dialect layer (ADR-0010): turns the SQL the core writes (SQLite flavour, `?` placeholders) into what another database
 * understands, and reports what cannot be turned automatically. Pure functions, no driver: `@das-forge/db-postgres` calls
 * `translate(sql, 'postgres')` before every statement; SQLite statements pass through untouched.
 *
 * What is translated: placeholders (`?` -> `$1, $2, ...`, quoted text and comments are left alone), the UTC timestamp default
 * `datetime('now')`, `INTEGER PRIMARY KEY AUTOINCREMENT`, `INTEGER` (to 64-bit `BIGINT`), `INSERT OR IGNORE`, `BLOB`, and `COLLATE NOCASE` in column
 * definitions (a `citext`-free rewrite is not possible there, so it is reported, see `findSqliteOnly`).
 * What is not translated but REPORTED: `PRAGMA`, `INSERT OR REPLACE`, FTS5, `julianday`/`strftime`, `rowid`, `GLOB`, `VACUUM`
 * - code reaches those through `dialect`-aware helpers instead.
 */

const PG_NOW = `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')`;

/** Applies `fn` to the parts of `sql` that are neither quoted text, quoted identifiers nor comments. */
function mapCode(sql, fn) {
  let out = '';
  let code = '';
  const flush = () => { out += fn(code); code = ''; };
  for (let i = 0; i < sql.length; i += 1) {
    const c = sql[i];
    const next = sql[i + 1];
    if (c === "'" || c === '"') {
      flush();
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === c) { if (sql[j + 1] === c) { j += 2; continue; } break; }
        j += 1;
      }
      out += sql.slice(i, j + 1);
      i = j;
    } else if (c === '-' && next === '-') {
      flush();
      const j = sql.indexOf('\n', i);
      const end = j === -1 ? sql.length : j;
      out += sql.slice(i, end);
      i = end - 1;
    } else if (c === '/' && next === '*') {
      flush();
      const j = sql.indexOf('*/', i + 2);
      const end = j === -1 ? sql.length : j + 2;
      out += sql.slice(i, end);
      i = end - 1;
    } else {
      code += c;
    }
  }
  flush();
  return out;
}

/** `?` -> `$1, $2, ...` outside quoted text and comments. */
export function numberPlaceholders(sql) {
  let n = 0;
  return mapCode(sql, (code) => code.replace(/\?/g, () => `$${++n}`));
}

/** Number of `?` placeholders in a statement (outside quoted text and comments). */
export function countPlaceholders(sql) {
  let n = 0;
  mapCode(sql, (code) => { n += (code.match(/\?/g) ?? []).length; return code; });
  return n;
}

const TRANSLATIONS = [
  // `datetime('now')` is quoted text, so the generic code mapper would skip it: handled on the whole statement first.
  [/\bdatetime\(\s*'now'\s*\)/gi, PG_NOW],
  [/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'],
];

/**
 * Translates one statement for `dialect`. SQLite (or an unknown dialect) returns the statement unchanged.
 * @param {string} sql
 * @param {'sqlite'|'postgres'} dialect
 * @returns {string}
 */
export function translate(sql, dialect) {
  if (dialect !== 'postgres') return sql;
  let out = sql;
  for (const [from, to] of TRANSLATIONS) out = out.replace(from, to);
  // BLOB is a type only in a table definition (a column may well be called `blob` in a query); there it follows the column name
  if (/^\s*(CREATE|ALTER)\b/i.test(out)) out = out.replace(/(?<=[\w"`\]]\s+)BLOB\b/gi, 'BYTEA');
  // PostgreSQL INTEGER is 32 bit; the core keeps millisecond timestamps and counters in INTEGER columns, SQLite's is 64 bit
  out = mapCode(out, (code) => code.replace(/\bINTEGER\b/gi, 'BIGINT'));
  // INSERT OR IGNORE INTO t (...) VALUES (...)  ->  INSERT INTO t (...) VALUES (...) ON CONFLICT DO NOTHING
  if (/^\s*INSERT\s+OR\s+IGNORE\s+INTO\b/i.test(out)) {
    out = out.replace(/^(\s*)INSERT\s+OR\s+IGNORE\s+INTO\b/i, '$1INSERT INTO').replace(/;?\s*$/, ' ON CONFLICT DO NOTHING');
  }
  return numberPlaceholders(out);
}

/** Splits a script of several statements on `;` outside quoted text and comments (for drivers that run one statement at a time). */
export function splitStatements(script) {
  const masked = mapCode(script, (code) => code.replace(/;/g, '\u0000'));
  const parts = [];
  let start = 0;
  for (let k = 0; k < masked.length; k += 1) {
    if (masked[k] === '\u0000') { parts.push(script.slice(start, k).trim()); start = k + 1; }
  }
  parts.push(script.slice(start).trim());
  return parts.filter(Boolean);
}

const SQLITE_ONLY = [
  [/\bPRAGMA\b/i, 'PRAGMA (use the dialect-aware helper)'],
  [/\bINSERT\s+OR\s+REPLACE\b/i, 'INSERT OR REPLACE (use INSERT ... ON CONFLICT (key) DO UPDATE)'],
  [/\bUSING\s+fts5\b|\bVIRTUAL\s+TABLE\b|\bMATCH\b/i, 'FTS5 full-text search (PostgreSQL: tsvector + GIN)'],
  [/\bjulianday\s*\(|\bstrftime\s*\(/i, 'julianday()/strftime() (compute the time in JavaScript)'],
  [/\browid\b/i, 'rowid'],
  [/\bGLOB\b/i, 'GLOB'],
  [/\bVACUUM\b/i, 'VACUUM (run outside a transaction; the helper handles it)'],
  [/\bCOLLATE\s+NOCASE\b/i, 'COLLATE NOCASE (compare with lower(...) or use citext)'],
  [/\bWITHOUT\s+ROWID\b/i, 'WITHOUT ROWID'],
  [/\bAUTOINCREMENT\b/i, 'AUTOINCREMENT outside "INTEGER PRIMARY KEY AUTOINCREMENT"'],
];

/**
 * What in a statement still needs SQLite after `translate(sql, 'postgres')`. Used by the dialect test and by `doctor`
 * to list what blocks PostgreSQL support.
 * @returns {string[]}
 */
export function findSqliteOnly(sql) {
  const visible = [];
  mapCode(translate(sql, 'postgres'), (part) => { visible.push(part); return part; });
  const text = visible.join(' ');
  return SQLITE_ONLY.filter(([re]) => re.test(text)).map(([, why]) => why);
}
