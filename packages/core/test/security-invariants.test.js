import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Source-level guards: patterns that must not appear in the core, or appear only where reviewed.
 * A new occurrence fails the test; to accept it, review it and add it to the allowlist with the reason.
 */
const SRC = fileURLToPath(new URL('../src/', import.meta.url));
function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = path.join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.js') ? [p] : [];
  });
}
const files = walk(SRC).map((f) => ({ rel: path.relative(SRC, f).split(path.sep).join('/'), text: readFileSync(f, 'utf8') }));
const hits = (re) => files.flatMap((f) => (f.text.match(re) ?? []).map(() => f.rel));
const uniq = (a) => [...new Set(a)].sort();

describe('dangerous constructs', () => {
  it('no eval, new Function or child_process', () => {
    expect(hits(/\beval\(|new Function\(/g)).toEqual([]);
    expect(hits(/child_process/g)).toEqual([]);
  });
  it('no md5 / sha1 digests', () => {
    // SHA-1 only to look a password up in a leaked-password list that is published as SHA-1 hashes (never to store or sign anything).
    expect(hits(/createHash\(\s*['"](md5|sha1)['"]/g).filter((f) => f !== 'auth/password-blocklist.js')).toEqual([]);
  });
  it('certificate verification is never switched off in code; only a reviewed, explicitly named option does it', () => {
    const allowed = { 'ldap/index.js': 'insecureTls option, off by default, flagged by the doctor' };
    expect(uniq(hits(/rejectUnauthorized\s*[:=]\s*false/g))).toEqual(Object.keys(allowed));
  });
  it('innerHTML / document.write only where the markup is trusted', () => {
    const allowed = { 'accounts/pages.js': 'QR SVG generated by this server' };
    expect(uniq(hits(/innerHTML|outerHTML|insertAdjacentHTML|document\.write/g))).toEqual(Object.keys(allowed));
  });
  it('VACUUM INTO always takes a bound parameter', () => {
    const bad = files.flatMap((f) => [...f.text.matchAll(/VACUUM INTO\s*(?!\?)['"$]/g)].map(() => f.rel));
    expect(bad).toEqual([]);
  });
});

describe('SQL is not built from values', () => {
  // db.run/get/all/exec/prepare with a template literal that interpolates something.
  const re = /\bdb\.(?:run|get|all|exec|prepare)\(\s*`[^`]*\$\{/g;
  const allowed = {
    'audit/query.js': 'where-clause assembled from fixed fragments, values bound',
    'auth/user-admin.js': 'where-clause assembled from fixed fragments, values bound',
    'branding/company-branding.js': 'constant table name',
    'database/fts.js': 'identifiers pass assertSafeIdentifier',
    'database/helpers.js': 'identifiers pass assertSafeIdentifier',
    'email/queue.js': 'constant WHERE fragment chosen in code',
    'database/sqlite-adapter.js': 'numeric pragma value',
    'admin/sections.js': 'only a run of ? placeholders sized by the id list, values bound',
    'notifications/index.js': 'constant WHERE fragment chosen in code',
    'security/bans.js': 'constant SQL fragment',
  };
  it('interpolation is limited to reviewed files', () => {
    const extra = uniq(hits(re)).filter((f) => !Object.hasOwn(allowed, f));
    expect(extra).toEqual([]);
  });
  it('files that interpolate identifiers validate them first', () => {
    for (const f of ['database/fts.js', 'database/helpers.js']) expect(files.find((x) => x.rel === f).text).toContain('assertSafeIdentifier(');
  });
});

describe('file names that come from outside', () => {
  it('backup destinations join only checked plain names', () => {
    const t = files.find((f) => f.rel === 'scheduler/backup-remote.js').text;
    expect(t).toContain('assertPlainName(');
    for (const m of t.matchAll(/path\.join\(root,\s*([^)]*)\)/g)) {
      if (m[1].trim() === 'cfg.markerFile' || m[1].trim() === 'name') continue; // marker: from the configuration; name: list() entries filtered by isBackupFileName
      expect(m[1]).toContain('assertPlainName(');
    }
  });
});
