import { describe, it, expect } from 'vitest';
import { createSqliteAdapter } from '../src/database/index.js';
import { columnsAsync, hasColumnAsync } from '../src/database/helpers-async.js';
import { translate, numberPlaceholders, countPlaceholders, splitStatements, findSqliteOnly } from '../src/database/dialect.js';

describe('dialect layer: placeholders', () => {
  it('numbers ? outside quoted text, quoted identifiers and comments', () => {
    expect(numberPlaceholders('SELECT * FROM t WHERE a = ? AND b = \'?\' AND c = ? -- why?\n AND "d?" = ? /* ? */')).toBe(
      'SELECT * FROM t WHERE a = $1 AND b = \'?\' AND c = $2 -- why?\n AND "d?" = $3 /* ? */'
    );
    expect(countPlaceholders("SELECT ? , 'it''s ?' , ?")).toBe(2);
  });
});

describe('dialect layer: translate', () => {
  it('leaves SQLite statements alone', () => {
    const sql = "INSERT OR IGNORE INTO t (a) VALUES (?) -- datetime('now')";
    expect(translate(sql, 'sqlite')).toBe(sql);
    expect(translate(sql, 'whatever')).toBe(sql);
  });
  it('turns the BLOB type into BYTEA but leaves a column that is called blob alone', () => {
    expect(translate('CREATE TABLE t (blob BLOB, "x" BLOB, y blob NOT NULL)', 'postgres')).toBe('CREATE TABLE t (blob BYTEA, "x" BYTEA, y BYTEA NOT NULL)');
    expect(translate('SELECT blob FROM t WHERE blob IS NOT NULL', 'postgres')).toBe('SELECT blob FROM t WHERE blob IS NOT NULL');
  });

  it('rewrites the timestamp default, identity columns and BLOB for PostgreSQL', () => {
    const out = translate("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT DEFAULT (datetime('now')), b BLOB)", 'postgres');
    expect(out).toContain('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(out).toContain("to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')");
    expect(out).toContain('b BYTEA');
    expect(out).not.toMatch(/AUTOINCREMENT|datetime|BLOB/);
  });
  it('widens INTEGER to BIGINT in code but not inside quoted text', () => {
    expect(translate("CREATE TABLE t (n INTEGER NOT NULL, k TEXT CHECK (k IN ('integer')))", 'postgres')).toBe("CREATE TABLE t (n BIGINT NOT NULL, k TEXT CHECK (k IN ('integer')))");
    expect(translate('SELECT CAST(x AS INTEGER)', 'postgres')).toBe('SELECT CAST(x AS BIGINT)');
  });
  it('turns INSERT OR IGNORE into ON CONFLICT DO NOTHING and numbers the placeholders', () => {
    expect(translate('INSERT OR IGNORE INTO t (a, b) VALUES (?, ?);', 'postgres')).toBe('INSERT INTO t (a, b) VALUES ($1, $2) ON CONFLICT DO NOTHING');
  });
});

describe('dialect layer: scripts and leftovers', () => {
  it('splits a script on ; outside quoted text', () => {
    expect(splitStatements("CREATE TABLE a (x TEXT DEFAULT ';'); CREATE INDEX i ON a(x);")).toEqual(["CREATE TABLE a (x TEXT DEFAULT ';')", 'CREATE INDEX i ON a(x)']);
  });
  it('reports what only SQLite understands, but not words inside quoted text', () => {
    expect(findSqliteOnly('SELECT 1')).toEqual([]);
    expect(findSqliteOnly("INSERT INTO t (note) VALUES ('PRAGMA rowid')")).toEqual([]);
    expect(findSqliteOnly('PRAGMA table_info(t)')).toHaveLength(1);
    expect(findSqliteOnly('INSERT OR REPLACE INTO t VALUES (?)')[0]).toMatch(/ON CONFLICT/);
    expect(findSqliteOnly('CREATE VIRTUAL TABLE x USING fts5(a)')[0]).toMatch(/tsvector/);
    expect(findSqliteOnly('SELECT strftime(\'%s\',created_at) FROM t')[0]).toMatch(/strftime/);
  });
});

describe('dialect layer: columns of a table', () => {
  it('lists columns with notnull for SQLite and answers hasColumn; an unknown table is empty', async () => {
    const db = createSqliteAdapter({ file: ':memory:' });
    db.exec('CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT NOT NULL, b TEXT)');
    expect((await columnsAsync(db, 't')).map((c) => [c.name, c.notnull])).toEqual([['id', 0], ['a', 1], ['b', 0]]);
    expect(await hasColumnAsync(db, 't', 'b')).toBe(true);
    expect(await hasColumnAsync(db, 't', 'zz')).toBe(false);
    expect(await columnsAsync(db, 'nope')).toEqual([]);
    await expect(columnsAsync(db, 'bad name;')).rejects.toThrow();
  });
});
